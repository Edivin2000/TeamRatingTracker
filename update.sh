#!/bin/bash

# Скрипт для обновления приложения ATOM-GAME Балаково
# ВНИМАНИЕ: Скрипт должен запускаться из корневой директории проекта

echo "=== Обновление ATOM-GAME Балаково ==="

# Создание резервной копии
echo "Создание резервной копии базы данных..."
./backup.sh backup

if [ $? -ne 0 ]; then
  echo "Ошибка при создании резервной копии! Обновление остановлено."
  exit 1
fi

# Скачивание последних изменений
echo "Получение последних изменений из репозитория..."
git pull

if [ $? -ne 0 ]; then
  echo "Ошибка при получении изменений! Обновление остановлено."
  exit 1
fi

# Установка зависимостей
echo "Обновление зависимостей..."
npm install

if [ $? -ne 0 ]; then
  echo "Ошибка при установке зависимостей! Обновление остановлено."
  exit 1
fi

# Сборка проекта
echo "Сборка проекта..."
npm run build

if [ $? -ne 0 ]; then
  echo "Ошибка при сборке проекта! Обновление остановлено."
  exit 1
fi

# Обновление базы данных
echo "Обновление схемы базы данных..."
npm run db:push

if [ $? -ne 0 ]; then
  echo "Ошибка при обновлении базы данных! Обновление остановлено."
  exit 1
fi

# Перезапуск приложения
echo "Перезапуск приложения..."
pm2 restart atom-game-blk

if [ $? -ne 0 ]; then
  echo "Ошибка при перезапуске приложения!"
  exit 1
fi

echo ""
echo "=== Обновление успешно завершено ==="
echo "Сайт доступен по адресу: http://atomgameblk.ru"
echo ""